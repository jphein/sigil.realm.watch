"""The WordPress binding names a build exactly as python does (issue #11).

wordpress/realm-sigil-version.php carries its own copy of the corpus, generated by
`./sync-words.sh --only wordpress` (it is part of `--all`). tools/audit_corpora.py proves the WORDS
match; this proves the NAMES do, by running the real PHP function against python's generate_name.

The PHP binding only ever names `substr(md5(...), 0, 7)`, a 7-hex-digit string, so that is the domain
compared here (it does not do python's 64-bit tolerant parse of arbitrary input; it never sees any).

PHP comes from $SIGIL_PHP (a command prefix, e.g. "docker run --rm -i php:8.3-cli php"), else `php` on
PATH. Without one the test skips locally, but FAILS under CI (GitHub sets CI=true; its ubuntu runners
ship php): a parity check that silently skips where it is supposed to run is not a check.

Run: python3 -m unittest discover -s python/tests
"""

import json
import os
import shlex
import shutil
import subprocess
import sys
import unittest

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
sys.path.insert(0, os.path.join(ROOT, "python"))

from realm_sigil import REALMS, generate_name  # noqa: E402

PHP_FILE = os.path.join(ROOT, "wordpress", "realm-sigil-version.php")

# Run with `php -r` (works for a local php and a docker one alike). The plugin's own source arrives on
# stdin and is eval'd: it is this repo's file, under test, in a throwaway php process; eval is the plain
# way to load source that is not on the php side's filesystem. add_action is the only WordPress call
# made at include time, so it is the only stub.
DRIVER = r"""
function add_action($hook, $cb) {}
eval('?>' . stream_get_line(STDIN, 1 << 22, "\0"));
$cases = json_decode(stream_get_contents(STDIN), true);
$out = [];
foreach ($cases as $c) { $out[] = realm_sigil_generate_name($c[0], $c[1]); }
echo json_encode($out, JSON_UNESCAPED_UNICODE);
"""


def _php():
    cmd = os.environ.get("SIGIL_PHP")
    if cmd:
        return shlex.split(cmd)
    return ["php"] if shutil.which("php") else None


def _hashes():
    out, x = [], 0x9E3779B97F4A7C15
    for _ in range(200):
        x = (x * 6364136223846793005 + 1442695040888963407) % 2**64
        out.append(format(x, "016x")[:7])
    return out + ["0000000", "fffffff", "00000ff", "0000100", "abcdef0", "ABCDEF0"]


class WordpressParity(unittest.TestCase):
    def test_php_names_equal_python_names(self):
        php = _php()
        if php is None:
            if os.environ.get("CI"):
                self.fail("no php under CI: the WordPress parity check would silently not run")
            self.skipTest("no php (set SIGIL_PHP to a command prefix to run this)")
        realms = sorted(REALMS) + ["no-such-realm"]  # an unknown realm falls back to fantasy in both
        cases = [[h, r] for r in realms for h in _hashes()]
        plugin = open(PHP_FILE, "rb").read()
        r = subprocess.run(php + ["-r", DRIVER], input=plugin + b"\0" + json.dumps(cases).encode(),
                           capture_output=True, timeout=300)
        self.assertEqual(r.returncode, 0, r.stderr.decode(errors="replace")[-2000:])
        got = json.loads(r.stdout)
        want = [generate_name(h, r_) for h, r_ in cases]
        bad = [(c, g, w) for c, g, w in zip(cases, got, want) if g != w]
        self.assertEqual(len(got), len(cases))
        self.assertFalse(bad, "first mismatches: %r" % bad[:5])
        print("wordpress parity: %d names over %d realms agree" % (len(cases), len(realms)), file=sys.stderr)


if __name__ == "__main__":
    unittest.main()
